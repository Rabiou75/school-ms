import { writeFileSync } from 'node:fs';
import { join } from 'node:path';

const path = join(process.cwd(), 'apps/api/src/notifications/providers/email.provider.ts');
const L = (a) => a.join('\n');

const content = L([
  "import { Injectable, Logger } from '@nestjs/common';",
  "",
  "type EmailOpts = { to: string; subject: string; body: string; html?: string };",
  "type SmtpConfig = { host: string; port: number; user: string; pass: string; from: string };",
  "",
  "@Injectable()",
  "export class EmailProvider {",
  "  private readonly logger = new Logger(EmailProvider.name);",
  "  private transporter: any = null;",
  "  private loadedFor: string | null = null;",
  "",
  "  private async getTransporter(cfg: SmtpConfig) {",
  "    const key = cfg.host + ':' + cfg.port + ':' + cfg.user;",
  "    if (this.transporter && this.loadedFor === key) return this.transporter;",
  "",
  "    try {",
  "      const nodemailer = await import('nodemailer');",
  "      const port = Number(cfg.port) || 587;",
  "      const is465 = port === 465;",
  "",
  "      this.transporter = nodemailer.createTransport({",
  "        host: cfg.host,",
  "        port,",
  "        secure: is465,                    // true only for 465",
  "        requireTLS: !is465,               // force STARTTLS on 587/25",
  "        auth: cfg.user ? { user: cfg.user, pass: cfg.pass } : undefined,",
  "        connectionTimeout: 15000,",
  "        greetingTimeout: 15000,",
  "        socketTimeout: 30000,",
  "        tls: {",
  "          rejectUnauthorized: false,      // tolerate cert chain quirks",
  "          servername: cfg.host,",
  "        },",
  "        family: 4,                        // force IPv4 (IPv6 often hangs)",
  "      } as any);",
  "",
  "      // Verify the connection immediately so we surface errors early",
  "      await this.transporter.verify();",
  "",
  "      this.loadedFor = key;",
  "      this.logger.log('SMTP transporter ready: ' + key);",
  "      return this.transporter;",
  "    } catch (e: any) {",
  "      this.logger.error('SMTP transporter failed: ' + e.message);",
  "      this.transporter = null;",
  "      this.loadedFor = null;",
  "      return null;",
  "    }",
  "  }",
  "",
  "  async send(cfg: SmtpConfig, opts: EmailOpts): Promise<{ ok: boolean; providerId?: string; error?: string }> {",
  "    if (!cfg.host) return { ok: false, error: 'smtp_not_configured' };",
  "",
  "    const t = await this.getTransporter(cfg);",
  "    if (!t) return { ok: false, error: 'smtp_connection_failed' };",
  "",
  "    try {",
  "      const info = await t.sendMail({",
  "        from: cfg.from || 'School <no-reply@school.cm>',",
  "        to: opts.to,",
  "        subject: opts.subject,",
  "        text: opts.body,",
  "        html: opts.html || opts.body.replace(/\\n/g, '<br>'),",
  "      });",
  "      return { ok: true, providerId: info.messageId };",
  "    } catch (e: any) {",
  "      this.logger.error('Email send failed: ' + e.message);",
  "      // Reset transporter so a config change triggers a fresh connection",
  "      this.transporter = null;",
  "      this.loadedFor = null;",
  "      return { ok: false, error: e.message };",
  "    }",
  "  }",
  "}",
  ""
]);

writeFileSync(path, content, 'utf8');
console.log('OK patched EmailProvider — IPv4, timeouts, verify()');