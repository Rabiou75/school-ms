  "    if (!confirm('Creer un compte de connexion pour chaque parent qui n en a pas ?')) return;",
  "    setBusy(true); setErr(null); setParentResult(null);",
  "    try {",
  "      const res = await apiFetch('/api/v1/bulk-import/parents/generate', { method: 'POST' });",
