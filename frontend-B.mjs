  "        <button onClick={() => setTab('parents')} className={'border-b-2 px-4 py-2 text-sm ' + (tab === 'parents' ? 'border-brand-600 font-medium text-brand-700' : 'border-transparent text-gray-600')}>Comptes parents</button>",
  "      </div>",
  "",
  "      {err && <p className=\"mt-4 rounded border border-red-200 bg-red-50 p-3 text-sm text-red-800\">{err}</p>}",
