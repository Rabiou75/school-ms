  "  const locale = params.locale || 'fr';",
  "  const l: Lang = locale === 'en' || locale === 'ar' ? locale : 'fr';",
  "  const now = new Date();",
  "  const [year, setYear] = useState(now.getFullYear());",
  "  const [month, setMonth] = useState(now.getMonth() + 1);",
  "  const [items, setItems] = useState<any[]>([]);",
  "  const [err, setErr] = useState<string | null>(null);",
  "  const [ok, setOk] = useState<string | null>(null);",
  "  const [generating, setGenerating] = useState(false);",
  "",
  "  const load = () => {",
  "    setErr(null);",
  "    apiFetch('/api/v1/payroll?year=' + year + '&month=' + month)",
  "      .then((r) => r.ok ? r.json() : [])",
  "      .then((d) => setItems(Array.isArray(d) ? d : []))",
  "      .catch((e) => setErr(String(e)));",
  "  };",
  "  useEffect(load, [year, month]);",
  "",
  "  const generate = async () => {",
  "    const monthName = MONTHS[l][month - 1];",
  "    if (!confirm(fill(T.confirmGen[l], { month: monthName, year: String(year) }))) return;",
  "    setGenerating(true); setErr(null); setOk(null);",
  "    try {",
  "      const r = await apiFetch('/api/v1/payroll/generate', {",
  "        method: 'POST', body: JSON.stringify({ year, month }),",
  "      });",
  "      if (!r.ok) {",
  "        const txt = await r.text();",
  "        if (txt.includes('payroll_already_generated')) { setErr(T.errAlready[l]); setGenerating(false); return; }",
  "        if (txt.includes('no_active_staff')) { setErr(T.errNoStaff[l]); setGenerating(false); return; }",
  "        throw new Error(txt);",
  "      }",
  "      const result = await r.json();",
  "      setOk(fill(T.okCreated[l], { n: String(result.created) }));",
  "      load();",
  "    } catch (e: any) { setErr(String(e)); }",
  "    finally { setGenerating(false); }",
  "  };",
  "",
  "  const payAll = async () => {",
  "    if (!confirm(T.confirmPayAll[l])) return;",
  "    await apiFetch('/api/v1/payroll/pay-all', { method: 'POST', body: JSON.stringify({ year, month }) });",
  "    load();",
  "  };",
  "",
  "  const payOne = async (id: string) => {",
  "    await apiFetch('/api/v1/payroll/' + id + '/pay', { method: 'POST' });",
  "    load();",
  "  };",
  "",
  "  const updateDeduction = async (id: string, deductions: number) => {",
  "    await apiFetch('/api/v1/payroll/' + id, { method: 'PUT', body: JSON.stringify({ deductions }) });",
  "    load();",
  "  };",
  "",
  "  const remove = async (id: string) => {",
  "    if (!confirm(T.confirmDel[l])) return;",
  "    await apiFetch('/api/v1/payroll/' + id, { method: 'DELETE' });",
  "    load();",
  "  };",
  "",
  "  const downloadPdf = async (id: string) => {",
  "    try { await downloadPayslip(id, l); }",
  "    catch (e: any) { setErr(String(e)); }",
  "  };",
  "",
  "  const totalNet = items.reduce((a, i) => a + i.netPay, 0);",
  "  const totalPaid = items.filter((i) => i.paidAt).reduce((a, i) => a + i.netPay, 0);",
  "  const totalPending = totalNet - totalPaid;",
  "",
  "  return (",
  "    <div>",
  "      <div className=\"flex flex-wrap items-center justify-between gap-3\">",
  "        <div>",
  "          <h1 className=\"text-2xl font-bold\">{T.title[l]}</h1>",
  "          <p className=\"mt-1 text-sm text-gray-500\">{T.subtitle[l]}</p>",
  "        </div>",
  "        <div className=\"flex flex-wrap items-center gap-2\">",
  "          <select value={month} onChange={(e) => setMonth(Number(e.target.value))} className=\"rounded border px-3 py-2 text-sm\">",
  "            {MONTHS[l].map((m, i) => <option key={i} value={i + 1}>{m}</option>)}",
  "          </select>",
  "          <input type=\"number\" value={year} onChange={(e) => setYear(Number(e.target.value))} className=\"w-24 rounded border px-3 py-2 text-sm\" />",
  "          {items.length === 0 && (",
  "            <button onClick={generate} disabled={generating}",
  "                    className=\"rounded-lg bg-brand-600 px-4 py-2 text-sm text-white hover:bg-brand-700 disabled:opacity-50\">",
  "              {generating ? '...' : T.generate[l]}",
  "            </button>",
  "          )}",
  "          {items.length > 0 && totalPending > 0 && (",
  "            <button onClick={payAll} className=\"rounded-lg bg-green-600 px-4 py-2 text-sm text-white hover:bg-green-700\">",
  "              {T.markAllPaid[l]}",
  "            </button>",
  "          )}",
  "        </div>",
  "      </div>",
  "",
  "      {err && <p className=\"mt-4 rounded border border-red-200 bg-red-50 p-3 text-sm text-red-800\">{err}</p>}",
  "      {ok && <p className=\"mt-4 rounded border border-green-200 bg-green-50 p-3 text-sm text-green-800\">{ok}</p>}",
  "",
  "      {items.length > 0 && (",
  "        <div className=\"mt-6 grid grid-cols-1 gap-4 sm:grid-cols-3\">",
  "          <div className=\"rounded-xl border border-teal-200 bg-teal-50 p-4\">",
  "            <div className=\"text-xs uppercase text-teal-800 opacity-70\">{T.totalPayable[l]}</div>",
  "            <div className=\"mt-1 text-2xl font-bold text-teal-900\">{formatXAF(totalNet)}</div>",
  "          </div>",
  "          <div className=\"rounded-xl border border-green-200 bg-green-50 p-4\">",
  "            <div className=\"text-xs uppercase text-green-800 opacity-70\">{T.paid[l]}</div>",
  "            <div className=\"mt-1 text-2xl font-bold text-green-900\">{formatXAF(totalPaid)}</div>",
  "          </div>",
  "          <div className=\"rounded-xl border border-red-200 bg-red-50 p-4\">",
  "            <div className=\"text-xs uppercase text-red-800 opacity-70\">{T.pending[l]}</div>",
  "            <div className=\"mt-1 text-2xl font-bold text-red-900\">{formatXAF(totalPending)}</div>",
  "          </div>",
  "        </div>",
  "      )}",
  "",
  "      {items.length === 0 && !err && (",
  "        <p className=\"mt-8 rounded-lg border bg-white p-8 text-center text-gray-500\">",
  "          {fill(T.empty[l], { month: MONTHS[l][month - 1], year: String(year) })}",
  "        </p>",
  "      )}",
  "",
  "      {items.length > 0 && (",
  "        <div className=\"mt-6 overflow-x-auto rounded-lg border bg-white\">",
  "          <table className=\"w-full border-collapse text-sm\">",
  "            <thead className=\"bg-gray-50 text-left\">",
  "              <tr>",
  "                <th className=\"p-3 font-medium\">{T.employeeNo[l]}</th>",
  "                <th className=\"p-3 font-medium\">{T.name[l]}</th>",
  "                <th className=\"p-3 font-medium\">{T.position[l]}</th>",
  "                <th className=\"p-3 text-right font-medium\">{T.gross[l]}</th>",
  "                <th className=\"p-3 text-right font-medium\">{T.deductions[l]}</th>",
  "                <th className=\"p-3 text-right font-medium\">{T.net[l]}</th>",
  "                <th className=\"p-3 font-medium\">{T.status[l]}</th>",
  "                <th className=\"p-3\"></th>",
  "              </tr>",
  "            </thead>",
  "            <tbody>",
  "              {items.map((it) => (",
  "                <tr key={it.id} className=\"border-t hover:bg-gray-50\">",
  "                  <td className=\"p-3 font-mono text-xs\">{it.staff.employeeNo}</td>",
  "                  <td className=\"p-3 font-medium\">{it.staff.firstName} {it.staff.lastName}</td>",
  "                  <td className=\"p-3 text-xs text-gray-600\">{it.staff.position}</td>",
  "                  <td className=\"p-3 text-right\">{formatXAF(it.grossPay)}</td>",
  "                  <td className=\"p-3 text-right\">",
  "                    <input type=\"number\" min={0} value={it.deductions}",
  "                           onChange={(e) => updateDeduction(it.id, Number(e.target.value))}",
  "                           className=\"w-24 rounded border px-2 py-1 text-right text-xs\" />",
  "                  </td>",
  "                  <td className=\"p-3 text-right font-bold text-teal-700\">{formatXAF(it.netPay)}</td>",
  "                  <td className=\"p-3\">",
