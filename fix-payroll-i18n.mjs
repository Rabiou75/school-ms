  "                      (it.paidAt ? 'bg-green-100 text-green-800' : 'bg-yellow-100 text-yellow-800')}>",
  "                      {it.paidAt ? T.paidLabel[l] : T.pendingLabel[l]}",
  "                    </span>",
  "                  </td>",
